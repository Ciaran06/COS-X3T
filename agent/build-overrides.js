#!/usr/bin/env node
/* Writes the assistant's tool definitions and system prompt into index.html.
 *
 * Vapi will take tools as a call override, but only inside a whole model
 * object — provider and model are required fields on it and the system prompt
 * lives in the same object — so the app has to carry both. This keeps the copy
 * in the page generated from the two files that are the source of truth, and
 * `node agent/build-overrides.js --check` fails if they have drifted, which is
 * what the test suite runs.
 *
 *   node agent/build-overrides.js          rewrite the block in index.html
 *   node agent/build-overrides.js --check  exit 1 if it is out of date
 */
const fs = require('fs');
const path = require('path');
const ROOT = path.join(__dirname, '..');

const BEGIN = '/* ===AGENT-OVERRIDES:BEGIN — generated by agent/build-overrides.js=== */';
const END   = '/* ===AGENT-OVERRIDES:END=== */';

/* the prompt is what sits between the two rules in the markdown */
function prompt(){
  const md = fs.readFileSync(path.join(ROOT,'agent','system-prompt.md'),'utf8');
  const parts = md.split('\n---\n');
  if(parts.length < 3) throw new Error('system-prompt.md no longer has the two rules around the prompt');
  return parts[1].trim();
}
function tools(){
  return JSON.parse(fs.readFileSync(path.join(ROOT,'agent','tools.json'),'utf8'));
}
function block(){
  return BEGIN + '\n'
    + '/* The eleven tools, sent as a call override so they do not have to be\n'
    + '   created by hand in the dashboard. Source: agent/tools.json. */\n'
    + 'const VAPI_TOOLS = ' + JSON.stringify(tools(), null, 2) + ';\n'
    + '/* The assistant’s system prompt. Source: agent/system-prompt.md. It has to\n'
    + '   travel with the tools because Vapi’s model override is a whole object,\n'
    + '   not a patch — sending tools without it would leave the call with no\n'
    + '   system prompt at all. */\n'
    + 'const VAPI_PROMPT = ' + JSON.stringify(prompt()) + ';\n'
    + END;
}
function apply(check){
  const file = path.join(ROOT,'index.html');
  const html = fs.readFileSync(file,'utf8');
  const i = html.indexOf(BEGIN), j = html.indexOf(END);
  if(i < 0 || j < 0) throw new Error('markers not found in index.html');
  const now  = html.slice(i, j + END.length);
  const want = block();
  if(now === want){ console.log('agent overrides: up to date'); return 0; }
  if(check){
    console.error('agent overrides: index.html is out of date — run `node agent/build-overrides.js`');
    return 1;
  }
  fs.writeFileSync(file, html.slice(0,i) + want + html.slice(j + END.length));
  console.log('agent overrides: index.html rewritten');
  return 0;
}
if(require.main === module) process.exit(apply(process.argv.includes('--check')));
module.exports = { block, prompt, tools, BEGIN, END };
